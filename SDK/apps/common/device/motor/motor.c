#if (RDX_SUPPORT_MOTOR == 1)

/******************************************************************************
* Macro Define Section
******************************************************************************/ 
#define MOTOR_CTRL_IO					IO_PORTB_02
#define MOTOR_CTRL_PIN					PORT_PIN_2
#define MOTOR_CTRL_PORT					PORTB

/******************************************************************************
* Local Variables Section
******************************************************************************/ 
static u16 motor_run_timer = 0;
static bool motor_run_flag = 0;

/******************************************************************************
* Function Declaration Section
******************************************************************************/ 
extern void rdx_app_emmc_poweron(u8 check_en);


/******************************************************************************
* Function Section
******************************************************************************/ 

/**************************************************************************
 * function: motor_on
 * description: 
 * param (*)
 * return (*)
 **************************************************************************/
void motor_on(void)
{
	/*----------------------------------------------------------------*/
	/* Local Variables                                                */
	/*----------------------------------------------------------------*/
	
	/*----------------------------------------------------------------*/
	/* Code Body                                                      */
	/*----------------------------------------------------------------*/
	rdx_app_emmc_poweron(1);
	
	gpio_write_port(MOTOR_CTRL_PORT, MOTOR_CTRL_PIN, 1);

	motor_run_flag = true;
}

/**************************************************************************
 * function: motor_off
 * description: 
 * param (*)
 * return (*)
 **************************************************************************/
void motor_off(void)
{
	/*----------------------------------------------------------------*/
	/* Local Variables                                                */
	/*----------------------------------------------------------------*/
	
	/*----------------------------------------------------------------*/
	/* Code Body                                                      */
	/*----------------------------------------------------------------*/
	if(motor_run_timer){
		usr_timeout_del(motor_run_timer);
		motor_run_timer = 0;
	}
	gpio_write_port(MOTOR_CTRL_PORT, MOTOR_CTRL_PIN, 0);

	motor_run_flag = false;
}

/**************************************************************************
 * function: motor_get_run_status
 * description: 
 * param (*)
 * return (*)
 **************************************************************************/
bool motor_get_run_status(void)
{ 
	/*----------------------------------------------------------------*/
	/* Local Variables                                                */
	/*----------------------------------------------------------------*/
	
	/*----------------------------------------------------------------*/
	/* Code Body                                                      */
	/*----------------------------------------------------------------*/
	return motor_run_flag;
}

/**************************************************************************
 * function: motor_run_cb
 * description: 
 * param (*)
 * return (*)
 **************************************************************************/
void motor_run_cb(void* priv)
{
	/*----------------------------------------------------------------*/
	/* Local Variables                                                */
	/*----------------------------------------------------------------*/
	
	/*----------------------------------------------------------------*/
	/* Code Body                                                      */
	/*----------------------------------------------------------------*/
    // gpio_write_port(PORTC, PORT_PIN_1, 0);
	motor_off();
	y_printf("===== %s --> motor off \r", __func__);
}

/**************************************************************************
 * function: motor_run_by_time
 * description: 
 * param (u16) ms
 * return (*)
 **************************************************************************/
void motor_run_by_time(u16 ms)
{
	/*----------------------------------------------------------------*/
	/* Local Variables                                                */
	/*----------------------------------------------------------------*/
	
	/*----------------------------------------------------------------*/
	/* Code Body                                                      */
	/*----------------------------------------------------------------*/
	// gpio_write_port(PORTC, PORT_PIN_1, 1);
	motor_off();
	motor_on();
	if(motor_run_timer == 0){
		motor_run_timer = usr_timeout_add(NULL, motor_run_cb, ms, 1);
	}
}

/**************************************************************************
 * function: motor_init
 * description: 
 * param (*)
 * return (*)
 **************************************************************************/
void motor_init(void)
{
	/*----------------------------------------------------------------*/
	/* Local Variables                                                */
	/*----------------------------------------------------------------*/
	
	/*----------------------------------------------------------------*/
	/* Code Body                                                      */
	/*----------------------------------------------------------------*/
	motor_run_flag = false;
	motor_run_timer = 0;

	//motor pin.
	struct gpio_config gpio_config_motor = {
		.pin = MOTOR_CTRL_PIN,
		.mode = PORT_OUTPUT_HIGH,
		.hd = PORT_DRIVE_STRENGT_64p0mA,
	};
	//配置PC1输出模式并输出0
	gpio_init(MOTOR_CTRL_PORT, &gpio_config_motor);

    motor_run_by_time(500);

    y_printf("===== %s --> motor init success \r", __func__);
}

#endif